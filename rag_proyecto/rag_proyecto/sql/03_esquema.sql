/* =====================================================================
   03_esquema.sql
   Proyecto: Mini sistema RAG con Oracle AI Database 26ai
   EJECUTAR: como RAG_USER, en FREEPDB1 (sesión nueva).

   DECISIONES DE DISEÑO
   1. Tres tablas encadenadas: documento -> seccion -> fragmento.
      La rúbrica exige registrar la procedencia de cada fragmento
      (documento y sección). Con esta cadena la procedencia queda en la
      base de datos y no depende del script. No se repite id_documento
      en fragmento: se obtiene con un JOIN a seccion (sin redundancia).
   2. El texto de cada sección se guarda completo en seccion.contenido.
      Así se puede volver a fragmentar con otro tamaño (por ejemplo 80 y
      150 palabras) sin releer los PDFs, y la comparación de estrategias
      de fragmentación del informe sale con los mismos datos.
   3. embedding VECTOR(384, FLOAT32): 384 es la dimensión de all-minilm.
      La dimensión debe coincidir con el modelo; si se cambia de modelo,
      hay que recrear la columna.
   4. Los vectores los genera Python y se guardan aquí (alternativa b del
      apartado 5.2 del enunciado), porque en la imagen lite no existe
      SYS.DBMS_NETWORK_ACL_ADMIN y la base no puede llamar a Ollama.
   ===================================================================== */

CREATE TABLE documento (
  id_documento  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo        VARCHAR2(200) NOT NULL,   -- p. ej. nombre del dispositivo
  fuente        VARCHAR2(400)             -- nombre del PDF o URL de origen
);

CREATE TABLE seccion (
  id_seccion    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_documento  NUMBER NOT NULL REFERENCES documento,
  titulo        VARCHAR2(300) NOT NULL,   -- título de la sección en el PDF
  pagina_inicio NUMBER,
  pagina_fin    NUMBER,
  contenido     CLOB NOT NULL             -- texto limpio de la sección
);

CREATE TABLE fragmento (
  id_fragmento  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_seccion    NUMBER NOT NULL REFERENCES seccion,
  posicion      NUMBER,                   -- posición del fragmento en la sección
  texto         VARCHAR2(4000) NOT NULL,
  embedding     VECTOR(384, FLOAT32)      -- se rellena desde Python
);

-- Acelera el JOIN de la búsqueda híbrida (filtro por documento).
CREATE INDEX ix_seccion_doc    ON seccion (id_documento);
CREATE INDEX ix_fragmento_secc ON fragmento (id_seccion);

-- VERIFICACIÓN: debe listar las tres tablas.
SELECT table_name FROM user_tables
WHERE  table_name IN ('DOCUMENTO', 'SECCION', 'FRAGMENTO')
ORDER  BY table_name;

